"""Generate localized parameter references from compiled task descriptors and i18n."""
import argparse
import json
import math
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
PATHS = {"zh": "docs/reference/task_parameters.md",
         "en": "docs/reference/task_parameters_en.md"}
WORDS = {
    "zh": {
        "title": "任务与参数参考", "contents": "目录", "default": "默认值",
        "values": "可选值", "range": "范围", "outputs": "输出", "empty": "空字符串",
        "condition": "显示条件", "none": "无",
        "intro": "本参考对应 Aster {version} 的任务定义。已有工作流保留其保存值；参数仍须通过任务的数据与约束校验。默认值不代表对研究数据的推荐设置。",
        "fallback": "缺少中文的条目使用英文。参数值和输出标识保留程序中的原始名称。",
        "links": "[使用手册](../USER_GUIDE.md) · [科学方法](../methods/README.md) · [English](task_parameters_en.md)",
        "file": "文件读取配置在输入面板中编辑；界面列号从 1 开始，内部参数列号从 0 开始。",
    },
    "en": {
        "title": "Task and parameter reference", "contents": "Contents", "default": "Default",
        "values": "Values", "range": "Range", "outputs": "Outputs", "empty": "empty string",
        "condition": "Shown when", "none": "None",
        "intro": "This reference describes task definitions in Aster {version}. Existing workflows retain saved values; data-specific checks and parameter constraints still apply. Defaults are not recommendations for a particular dataset.",
        "fallback": "Parameter values and output identifiers retain their original program names.",
        "links": "[User guide](../USER_GUIDE_EN.md) · [Methods (Chinese)](../methods/README.md) · [Chinese](task_parameters.md)",
        "file": "Edit file-reading settings in the input panel. Displayed column numbers start at 1; internal column parameters start at 0.",
    },
}


def translated(current, english, keys, fallback=""):
    """Match UI lookup: a task-specific English value precedes a generic label."""
    for key in keys:
        for catalog in (current, english):
            value = catalog.get(key)
            if isinstance(value, str) and value.strip():
                return value
    return fallback


def inline(value):
    """Escape a label, without changing the underlying program value."""
    return re.sub(r"([\\`*_{}\[\]<>#|])", r"\\\1", str(value).replace("\n", " "))


def code(value, words):
    if value == "":
        return words["empty"]
    if isinstance(value, str):
        raw = value
    else:
        raw = json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    # CommonMark code spans may contain backticks, but not their own delimiter.
    fence = "`" * (max((len(m[0]) for m in re.finditer(r"`+", raw)), default=0) + 1)
    return f"{fence} {raw} {fence}"


def validate(catalog, version):
    if catalog.get("schema") != 1 or catalog.get("version") != version:
        raise ValueError("Catalog schema/version mismatch; rebuild aster_help_catalog.")
    tasks = catalog.get("tasks")
    if not isinstance(tasks, list) or not tasks:
        raise ValueError("Empty or invalid task catalog.")
    methods = set()
    for task in tasks:
        key = task["key"]
        if not re.fullmatch(r"[a-zA-Z0-9_]+", key) or key in methods:
            raise ValueError(f"Invalid or duplicate task key: {key}")
        methods.add(key)
        parameters = set()
        for parameter in task["parameters"]:
            name = parameter["key"]
            if not re.fullmatch(r"[a-zA-Z0-9_]+", name) or name in parameters:
                raise ValueError(f"Invalid or duplicate parameter: {key}.{name}")
            parameters.add(name)


def render(catalog, catalogs, language):
    words = WORDS[language]
    current, english = catalogs[language], catalogs["en"]
    tasks = sorted(catalog["tasks"], key=lambda t: t["key"])

    def method_label(task):
        return translated(current, english, ["method." + task["key"]], task["label"])

    lines = [f'# {words["title"]}', "",
             "<!-- Generated by tools/help_reference/generate.py; edit task descriptors and resources/i18n instead. -->",
             "", words["links"], "", words["intro"].format(version=catalog["version"]), "",
             words["fallback"], "", f'## {words["contents"]}', ""]
    for task in tasks:
        lines.append(f'- [{inline(method_label(task))}](#m-{task["key"]})')
    for task in tasks:
        key = task["key"]
        lines += ["", f'<a id="m-{key}"></a>', f'## {inline(method_label(task))}', ""]
        help_text = translated(current, english, ["methodhelp." + key])
        if help_text:
            lines += [help_text, ""]
        if key == "file_source":
            lines += [words["file"], ""]
        for parameter in task["parameters"]:
            name = parameter["key"]
            label = translated(current, english,
                               [f"parameter.{key}.{name}", f"parameter.{name}"],
                               parameter["label"] or name)
            help_text = translated(current, english,
                                   [f"parameterhelp.{key}.{name}", f"parameterhelp.{name}"],
                                   parameter["help"])
            lines += [f'<a id="m-{key}-p-{name}"></a>', f'### {inline(label)}', ""]
            if help_text:
                lines += [help_text, ""]
            # The input panel applies detected file options over descriptor defaults.
            if key != "file_source":
                lines += [f'{words["default"]}: {code(parameter["default"], words)}', ""]
            if parameter["choices"]:
                lines += [f'{words["values"]}: ' + ", ".join(code(v, words) for v in parameter["choices"]), ""]
            if parameter["numeric"]:
                lo, hi = parameter["minimum"], parameter["maximum"]
                # Omit unconstrained +/- DBL_MAX sentinels from readable help.
                finite_lo = isinstance(lo, (int, float)) and math.isfinite(lo) and lo > -1e300
                finite_hi = isinstance(hi, (int, float)) and math.isfinite(hi) and hi < 1e300
                if finite_lo or finite_hi:
                    bounds = ((f'{json.dumps(lo)} ≤ ' if finite_lo else "") + name +
                              (f' ≤ {json.dumps(hi)}' if finite_hi else ""))
                    lines += [f'{words["range"]}: {code(bounds, words)}', ""]
            if parameter["visibleWhen"]:
                condition = "; ".join(f'{code(k, words)} = {code(v, words)}'
                                      for k, v in sorted(parameter["visibleWhen"].items()))
                lines += [f'{words["condition"]}: {condition}', ""]
        lines += [f'{words["outputs"]}: ' +
                  (", ".join(code(o, words) for o in task["outputs"]) or words["none"]), ""]
    return "\n".join(lines)


def synchronize(root, documents, check):
    changed = []
    for language, content in documents.items():
        path = root / PATHS[language]
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        changed.append(PATHS[language])
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", required=True, type=Path,
                        help="Aster build directory configured with CONFIG+=help_reference")
    parser.add_argument("--check", action="store_true", help="Fail on stale documents without writing")
    args = parser.parse_args()
    candidates = [args.build / "bin" / name for name in ("aster_help_catalog", "aster_help_catalog.exe")]
    executable = next((p.resolve() for p in candidates if p.is_file()), None)
    if executable is None:
        parser.error("Missing aster_help_catalog; configure with CONFIG+=help_reference and build first.")
    try:
        output = subprocess.run([str(executable)], check=True, capture_output=True,
                                text=True, encoding="utf-8", timeout=60)
        catalog = json.loads(output.stdout)
        validate(catalog, (ROOT / "VERSION").read_text(encoding="utf-8").strip())
        catalogs = {lang: json.loads((ROOT / f"resources/i18n/{lang}.json").read_text(encoding="utf-8"))
                    for lang in PATHS}
        documents = {lang: render(catalog, catalogs, lang) for lang in PATHS}
        changed = synchronize(ROOT, documents, args.check)
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as error:
        print(f"Parameter reference generation failed: {error}", file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr.strip(), file=sys.stderr)
        return 1
    if changed and args.check:
        print("Stale parameter references: " + ", ".join(changed), file=sys.stderr)
        print("Run this command without --check, rebuild and commit both documents.", file=sys.stderr)
        return 1
    print(f'{len(catalog["tasks"])} tasks / ' +
          f'{sum(len(t["parameters"]) for t in catalog["tasks"])} parameters; ' +
          ("updated " + ", ".join(changed) if changed else "both language references are current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
